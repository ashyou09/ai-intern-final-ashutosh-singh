from backend.exporter import _sanitize_latex, export_md, export_pdf, export_txt, markdown_to_text

FULL_REPORT = """# Quantum Computing in 2025

## Overview
Quantum computers use **qubits** [1]. Inline math `O(n log n)` and a link
[IBM](https://ibm.com/quantum).

## Key Findings
- Error rates fell — “significantly” [2]
- See [the paper](https://arxiv.org/abs/1)

```
(x + y)^n = Sum(k=0 to n) C(n,k) * x^(n-k) * y^k
```

| Company | Qubits |
|---|---|
| IBM | 1121 |

> A quoted line.

---

## Sources

1. [Quantum page](https://example.com/q) — Web
2. [A paper](https://arxiv.org/abs/1) — A, B, arXiv, 2024
"""


def test_export_pdf_full_report():
    data = export_pdf(FULL_REPORT, "quantum")
    assert data.startswith(b"%PDF")
    assert len(data) > 1000


def test_export_pdf_without_headings_uses_filename():
    assert export_pdf("Just one line of text.", "plain_title").startswith(b"%PDF")


def test_export_pdf_handles_non_latin_text():
    assert export_pdf("# 量子 计算\n\nEmoji 🚀 and Greek αβγ", "x").startswith(b"%PDF")


def test_export_txt_is_utf8():
    assert export_txt("héllo", "x").decode("utf-8").startswith("héllo\n")


def test_markdown_to_text():
    text = markdown_to_text(FULL_REPORT)
    lines = text.splitlines()
    assert lines[:2] == ["QUANTUM COMPUTING IN 2025", "========================="]
    assert "Overview" in lines and "--------" in lines
    assert "Quantum computers use qubits [1]. Inline math O(n log n) and a link" in text
    assert "IBM (https://ibm.com/quantum)." in text
    assert "    (x + y)^n = Sum(k=0 to n) C(n,k) * x^(n-k) * y^k" in lines
    assert "|---|---|" not in text
    assert "1. Quantum page (https://example.com/q) — Web" in text
    assert "**" not in text and "```" not in text


def test_markdown_to_text_keeps_bare_url_links_short():
    assert markdown_to_text("[https://a.com](https://a.com)") == "https://a.com\n"


def test_export_md_appends_footer():
    data = export_md("# T\n", "x").decode("utf-8")
    assert data.startswith("# T\n\n---\n\n*Generated by AI Research Assistant on ")


def test_pdf_has_page_numbers():
    long_report = "# Long\n\n" + "\n\n".join(f"Paragraph {i} " + "word " * 80 for i in range(40))
    data = export_pdf(long_report, "long")
    assert data.count(b"/Type /Page") > 2   # more than one page (plus the /Pages node)


def test_sanitize_latex():
    assert _sanitize_latex(r"\frac{a}{b}") == "(a)/(b)"
    assert _sanitize_latex(r"\binom{n}{k}") == "C(n, k)"
    assert _sanitize_latex(r"x^{n-k}") == "x^(n-k)"
